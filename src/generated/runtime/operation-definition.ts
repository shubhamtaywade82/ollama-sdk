/**
 * OperationDefinition — the runtime-facing contract shape.
 *
 * Every generated operation in `src/generated/api/operations.ts` is typed
 * `as const satisfies OperationDefinition`. This file is the ONLY hand-written
 * file in `src/generated/` — it defines the contract the generated code
 * expects the runtime to honor.
 *
 * The shape mirrors {@link OperationContract} from the canonical IR, with
 * one simplification: schema refs are typed as `$ref: string` rather than
 * the full `SchemaRef` interface, because the runtime never resolves them
 * (it just passes the request body to the HTTP client).
 *
 * The types below are intentionally inlined (not imported from
 * `generator/types.ts`) so that `src/generated/` is self-contained and
 * the shipped package does not depend on the build-time `generator/`
 * directory at runtime. The contract IR is regenerated by `npm run
 * contract:generate`; the canonical type definitions live in
 * `generator/types.ts`, and this file mirrors just the subset the runtime
 * needs.
 */

/** Wire-format used to transport request/response bodies. */
export type TransportMode = 'json' | 'ndjson' | 'sse';

/** HTTP method an operation uses. */
export type HttpMethod = 'GET' | 'POST' | 'DELETE' | 'PUT' | 'PATCH' | 'HEAD';

/** Capability support level — first-class concept in Ollama's docs. */
export type CapabilitySupport =
  'supported' | 'unsupported' | 'model-dependent' | 'version-dependent';

/** Schema reference, same shape as the IR's SchemaRef. */
export interface SchemaRef {
  readonly $ref: string;
}

/**
 * Wave 15 (P0): structural parameter on an operation. Mirrors
 * {@link OperationParameter} from the canonical IR. Path parameters
 * are substituted into the operation's path template at runtime;
 * query and header parameters are attached to the HTTP request.
 */
export interface OperationParameter {
  readonly name: string;
  readonly in: 'path' | 'query' | 'header';
  readonly required: boolean;
  readonly schema?: { readonly type?: string };
  readonly description?: string;
}

/** Behavioral contract a generated operation carries into the runtime. */
export interface OperationDefinition {
  readonly operationId: string;
  readonly method: HttpMethod;
  readonly path: string;
  readonly request?: SchemaRef;
  readonly response?: SchemaRef;
  readonly environment: {
    readonly local: boolean;
    readonly cloud: boolean;
  };
  /**
   * Wave 12 (P1 #7): host this operation targets, when different from
   * the runtime's default HttpClient base URL. Cloud-hosted capability
   * endpoints (web search, web fetch) live at `https://ollama.com/api/...`
   * rather than the local Ollama server. The runtime rejects operations
   * with a non-default host when the runtime's HttpClient isn't
   * configured for that host — callers must use OllamaClient.webSearch /
   * OllamaClient.webFetch (which spin up a dedicated cloud HttpClient)
   * for these operations.
   */
  readonly host?: string;
  /**
   * Wave 15 (P0): structural parameters derived from the path template
   * and OpenAPI declarations. Path parameters are substituted into the
   * URL at runtime; query and header parameters are attached to the
   * HTTP request. The runtime uses this to URI-encode and substitute
   * `{name}` segments in the path.
   */
  readonly parameters?: readonly OperationParameter[];
  readonly transport: {
    readonly mode: TransportMode;
    readonly streaming: boolean;
    readonly streamingDefault?: boolean;
  };
  readonly capabilities: {
    readonly thinking?: CapabilitySupport;
    readonly tools?: CapabilitySupport;
    readonly vision?: CapabilitySupport;
    readonly structuredOutput?: CapabilitySupport;
    readonly logprobs?: CapabilitySupport;
    readonly embeddings?: CapabilitySupport;
  };
  readonly constraints?: {
    readonly minOllamaVersion?: string;
    readonly maxRequestBytes?: number;
    /** Wave 13: limit when body contains images (e.g. System One: 32 MiB). */
    readonly maxRequestBytesWithImages?: number;
  };
  readonly status: {
    readonly documented: boolean;
    readonly deprecated?: boolean;
    readonly experimental?: boolean;
  };
  readonly domain: 'native' | 'openai' | 'anthropic';
  readonly notes?: readonly string[];
}

/** Request descriptor passed by generated API classes to {@link OllamaRuntime.invoke}. */
export interface InvokeRequest {
  /** The operation definition this call corresponds to. */
  readonly operation: OperationDefinition;
  /** Request body, or `undefined` for GET/HEAD calls. */
  readonly body: unknown;
  /** Optional per-call abort signal. */
  readonly signal?: AbortSignal;
  /**
   * Whether the docs say this operation streams by default. The runtime
   * uses this to decide whether to enable streaming when the request body
   * doesn't explicitly set `stream`.
   */
  readonly streamingDefault?: boolean;
  /**
   * Wave 15 (P0): path parameter values keyed by parameter name. The
   * runtime substitutes these into the operation's path template
   * (e.g. `{model}` → `gpt-4`) with URI encoding.
   */
  readonly pathParams?: Readonly<Record<string, string>>;
  /**
   * Wave 15 (P0): query parameter values keyed by parameter name.
   * The runtime attaches these to the HTTP request URL.
   */
  readonly queryParams?: Readonly<Record<string, string>>;
  /**
   * Wave 15 (P0): header parameter values keyed by header name.
   * The runtime attaches these to the HTTP request headers.
   */
  readonly headerParams?: Readonly<Record<string, string>>;
  /**
   * Wave 15 (P1): model name for routing. Extracted from the request
   * body when possible; used by the failover layer to filter endpoints
   * by `OllamaEndpoint.models` (credential-scoped routing).
   */
  readonly model?: string;
}
